        /// <summary>Returns a copy of the full city catalogue.</summary>
        public static List<City> Cities() => new List<City>(All);

        /// <summary>Returns the number of cities in the catalogue.</summary>
        public static int Count => All.Count;

        /// <summary>
        /// Looks a city up by its token. Returns null when the token is unknown.
        /// </summary>
        public static City Find(string token)
        {
            if (string.IsNullOrEmpty(token)) return null;
            foreach (var c in All)
            {
                if (string.Equals(c.Token, token, System.StringComparison.OrdinalIgnoreCase))
                {
                    return c;
                }
            }
            return null;
        }

        /// <summary>
        /// Returns a human-readable name for a token, falling back to the
        /// token itself when the city is not in the catalogue.
        /// </summary>
        public static string DisplayName(string token)
        {
            var city = Find(token);
            if (city != null && !string.IsNullOrEmpty(city.Name)) return city.Name;
            return token ?? string.Empty;
        }
