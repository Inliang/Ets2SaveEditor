        /// <summary>
        /// 查询显示名；查不到时返回空串（调用方决定如何回退）。
        /// </summary>
        public static string Lookup(Dictionary<string, string> table, string token)
        {
            if (table == null || string.IsNullOrEmpty(token)) return string.Empty;
            string name;
            if (!table.TryGetValue(token, out name)) return string.Empty;

            // 少数名称在游戏数据里是本地化占位符（@@cn_xxx@@），而对应条目
            // 在当前语言包中不存在（例如只随 DLC 提供的货物）。这时不要把
            // 占位符原样显示出去，返回空串让调用方回退到 token。
            if (name.StartsWith("@@", StringComparison.Ordinal)) return string.Empty;
            return name;
        }
