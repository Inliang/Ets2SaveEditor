using System;
using System.Collections.Generic;

namespace Ets2SaveEditor.Core.Sii.Model
{
    /// <summary>
    /// A generic SII unit (lossless representation). Unknown fields are preserved
    /// in <see cref="RawLines"/> so that saving never corrupts the save file.
    /// </summary>
    public class SiiUnit
    {
        /// <summary>Unit type (e.g. "bank", "garage").</summary>
        public string Type { get; set; }

        /// <summary>Unit identifier (e.g. "_nameless.000").</summary>
        public string Id { get; set; }

        /// <summary>Parsed attributes.</summary>
        public List<SiiAttribute> Attributes { get; set; }

        /// <summary>Lines that could not be parsed / nested structures, kept verbatim.</summary>
        public List<string> RawLines { get; set; }

        public SiiUnit()
        {
            Type = string.Empty;
            Id = string.Empty;
            Attributes = new List<SiiAttribute>();
            RawLines = new List<string>();
        }

        public SiiUnit(string type, string id) : this()
        {
            Type = type ?? string.Empty;
            Id = id ?? string.Empty;
        }

        /// <summary>Returns the attribute with the given name, or null if not found.</summary>
        public SiiAttribute GetAttribute(string name)
        {
            if (string.IsNullOrEmpty(name)) return null;
            foreach (var a in Attributes)
            {
                if (a != null && a.Name == name) return a;
            }
            return null;
        }

        /// <summary>Replaces an existing attribute value or adds a new one.</summary>
        public void SetAttribute(string name, SiiValue value)
        {
            if (string.IsNullOrEmpty(name)) return;
            var existing = GetAttribute(name);
            if (existing != null)
            {
                existing.Value = value;
                existing.IsArray = false;
            }
            else
            {
                Attributes.Add(new SiiAttribute(name, value));
            }
        }

        /// <summary>Removes the attribute with the given name.</summary>
        public void RemoveAttribute(string name)
        {
            if (string.IsNullOrEmpty(name)) return;
            Attributes.RemoveAll(a => a != null && a.Name == name);
        }

        public string GetString(string name)
        {
            var a = GetAttribute(name);
            if (a == null) return string.Empty;
            if (a.Value is StringValue sv) return sv.Value;
            if (a.Value is ReferenceValue rv) return rv.TargetId;
            return string.Empty;
        }

        public long GetLong(string name)
        {
            var a = GetAttribute(name);
            if (a == null) return 0;
            if (a.Value is IntValue iv) return iv.Value;
            if (a.Value is FloatValue fv) return (long)fv.Value;
            return 0;
        }

        public double GetDouble(string name)
        {
            var a = GetAttribute(name);
            if (a != null)
            {
                if (a.Value is FloatValue fv) return fv.Value;
                if (a.Value is IntValue iv) return iv.Value;
            }
            return 0;
        }

        public bool GetBool(string name)
        {
            var a = GetAttribute(name);
            if (a != null && a.Value is BoolValue bv) return bv.Value;
            return false;
        }

        public string GetReference(string name)
        {
            var a = GetAttribute(name);
            if (a != null && a.Value is ReferenceValue rv) return rv.TargetId;
            return string.Empty;
        }

        /// <summary>
        /// Returns the items of an array attribute. A single value is returned
        /// as a single-item list so callers do not have to special-case it.
        /// </summary>
        public List<SiiValue> GetArrayItems(string name)
        {
            var result = new List<SiiValue>();
            var a = GetAttribute(name);
            if (a == null) return result;

            if (a.IsArray && a.Value is ArrayValue arr)
            {
                result.AddRange(arr.Items);
            }
            else if (a.Value != null)
            {
                result.Add(a.Value);
            }

            return result;
        }

        /// <summary>
        /// Replaces an array attribute with the given items. The element count
        /// is regenerated by the serializer.
        /// </summary>
        public void SetArrayItems(string name, List<SiiValue> items)
        {
            if (string.IsNullOrEmpty(name)) return;
            var existing = GetAttribute(name);
            if (existing != null)
            {
                existing.Value = new ArrayValue(items);
                existing.IsArray = true;
            }
            else
            {
                Attributes.Add(new SiiAttribute(name, new ArrayValue(items)) { IsArray = true });
            }
        }

        // ---- SetScalar overloads (write typed values into attributes) ----

        public void SetScalar(string name, long value) => SetAttribute(name, new IntValue(value));

        public void SetScalar(string name, long? value) => SetAttribute(name, new IntValue(value ?? 0));

        /// <summary>
        /// Writes a floating point value. When the current value uses the game's
        /// hexadecimal notation the notation is preserved, so the save file keeps
        /// the exact same representation.
        /// </summary>
        public void SetScalar(string name, double value)
        {
            var existing = GetAttribute(name);
            bool isHex = existing != null && existing.Value is FloatValue current && current.IsHex;
            SetAttribute(name, new FloatValue(value, isHex));
        }

        /// <summary>
        /// Writes a float attribute using the representation the game itself
        /// uses: integral values are written as plain integers, fractional
        /// values as IEEE-754 bit patterns (<c>&amp;xxxxxxxx</c>). The game
        /// never writes decimal fractions, so this keeps the file loadable.
        /// </summary>
        public void SetFloat(string name, double value)
        {
            float single = (float)value;
            if (!float.IsNaN(single) && !float.IsInfinity(single) &&
                single == MathF.Floor(single) && MathF.Abs(single) < 1e7f)
            {
                SetAttribute(name, new IntValue((long)single));
                return;
            }

            SetAttribute(name, new FloatValue(single, true));
        }

        public void SetScalar(string name, bool value) => SetAttribute(name, new BoolValue(value));

        public void SetScalar(string name, string value) => SetAttribute(name, new StringValue(value));

        /// <summary>
        /// Writes a textual value while keeping the representation style of the
        /// current attribute: a bare reference (e.g. <c>scania_s_2024e</c>)
        /// stays bare, a quoted string (e.g. <c>"sanbuilders.london"</c>) stays
        /// quoted. This avoids pointless textual differences when the user
        /// edits a field that the game wrote in a specific style.
        /// </summary>
        public void SetScalarPreserveStyle(string name, string value)
        {
            string text = value ?? string.Empty;
            var existing = GetAttribute(name);

            if (existing != null)
            {
                if (existing.Value is StringValue)
                {
                    SetAttribute(name, new StringValue(text));
                    return;
                }

                if (existing.Value is ReferenceValue)
                {
                    SetAttribute(name, new ReferenceValue(text));
                    return;
                }
            }

            SetAttribute(name, CreateTextValue(text));
        }

        /// <summary>
        /// Creates the value the game itself would use for the given text:
        /// plain identifiers (letters, digits and underscore) are written
        /// bare, everything else is quoted.
        /// </summary>
        public static SiiValue CreateTextValue(string text)
        {
            if (string.IsNullOrEmpty(text)) return new StringValue(text);

            foreach (char c in text)
            {
                bool allowed = (c >= 'a' && c <= 'z') ||
                               (c >= 'A' && c <= 'Z') ||
                               (c >= '0' && c <= '9') ||
                               c == '_';
                if (!allowed)
                {
                    return new StringValue(text);
                }
            }

            return new ReferenceValue(text);
        }

        public void SetScalar(string name, ReferenceValue value) => SetAttribute(name, value);
    }
}
